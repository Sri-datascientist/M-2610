def get_ayush_board_details(state_name: str) -> Dict[str, Any]:
    cleaned = state_name.strip().lower()
    
    # Common normalization aliases from postal APIs
    aliases = {
        "orissa": "Odisha",
        "pondicherry": "Puducherry",
        "delhi": "Delhi",
        "nct of delhi": "Delhi",
        "jammu & kashmir": "Jammu and Kashmir",
        "andaman & nicobar": "Andaman and Nicobar Islands",
        "andaman & nicobar islands": "Andaman and Nicobar Islands",
        "dadra and nagar haveli": "Dadra and Nagar Haveli and Daman and Diu",
        "daman and diu": "Dadra and Nagar Haveli and Daman and Diu",
    }
    
    target_key = aliases.get(cleaned)
    if target_key and target_key in AYUSH_FULL_REGISTRY:
        return AYUSH_FULL_REGISTRY[target_key]

    for key, data in AYUSH_FULL_REGISTRY.items():
        if key.lower() == cleaned:
            return data
            
    return {
        **CENTRAL_JURISDICTION_DEFAULT,
        "region_note": f"Region '{state_name}' is mapped to Central oversight under the NCISM Act."
    }
